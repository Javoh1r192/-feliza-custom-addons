# -*- coding: utf-8 -*-
from odoo import fields, models


class StockWarehouse(models.Model):
    _inherit = 'stock.warehouse'

    # ------------------------------------------------------------------
    #  Магазины оформляют заявки на ОСНОВНОЙ склад. Чтобы при выборе
    #  товара сразу было видно, есть ли он там, на карточке каталога
    #  показывается второй остаток — по складу, отмеченному этим полем.
    #
    #  Поле, а не жёстко прописанное имя склада: основной склад может
    #  смениться, и тогда достаточно переставить галочку.
    # ------------------------------------------------------------------
    feliza_catalog_main = fields.Boolean(
        string="Основной склад (показывать остаток в каталоге)",
        help="На карточках каталога, кроме остатка в текущем документе, "
             "будет показан остаток этого склада. Можно отметить несколько складов — покажется строка на каждый (максимум 3).",
    )
